import type { ReactNode } from 'react';
import { cx } from './cx';

// Inline SVG icons (research R-11): stroke icons on a 24 × 24 grid in the current text
// colour. Decorative by default (hidden from assistive technology); with a `title` the icon
// is an image with that name.

interface IconProps {
  className?: string;
  title?: string;
}

function Icon({ className, title, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={cx('size-5 shrink-0', className)}
      {...(title ? { role: 'img', 'aria-label': title } : { 'aria-hidden': true })}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}

